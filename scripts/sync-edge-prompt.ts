// Copies the reminder prompt (prompts/reminder-draft/v1) into the demonstration Edge Function, which can't read
// files beside it once deployed. Run it after changing the prompt: node scripts/sync-edge-prompt.ts
// jobs/test/edge-function.test.ts fails while the copy differs from the prompt files.
import { readFileSync, writeFileSync } from 'node:fs';
import { isMain } from '../jobs/lib/run.ts';

const root = new URL('../', import.meta.url);
export const EDGE_PROMPT_FILE = new URL('supabase/functions/demo-weekly-run/prompt.ts', root);

/** The prompt module's text, made from the prompt files as they are now. */
export const edgePromptSource = (): string => {
  const system = readFileSync(new URL('prompts/reminder-draft/v1/system.md', root), 'utf8');
  const schema = JSON.parse(readFileSync(new URL('prompts/reminder-draft/v1/output.schema.json', root), 'utf8')) as unknown;
  return [
    '// Generated by scripts/sync-edge-prompt.ts from prompts/reminder-draft/v1. Do not edit by hand.',
    '// The Edge Function is deployed without the prompt files, so it carries this copy (jobs/test/edge-function.test.ts).',
    '',
    `export const SYSTEM_PROMPT: string = ${JSON.stringify(system)};`,
    '',
    `export const OUTPUT_SCHEMA: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};`,
    '',
  ].join('\n');
};

if (isMain(import.meta.url)) {
  writeFileSync(EDGE_PROMPT_FILE, edgePromptSource());
  console.log('Wrote supabase/functions/demo-weekly-run/prompt.ts');
}
